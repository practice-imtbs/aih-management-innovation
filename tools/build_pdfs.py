"""Génère les PDF des scripts (FR et EN) aux couleurs IMT-BS.

FR : texte lu dans ../03_Scripts-capsules/<NN_slug>/AIH_script.md (entre les deux lignes ---).
EN : traduction fidèle dans tools/scripts_en.json.
Sortie : scripts/AIH_Capsule<N>_Script_<FR|EN>.pdf

Usage : python3 tools/build_pdfs.py
"""
import glob
import json
import re
from pathlib import Path

from reportlab.lib.colors import HexColor, white
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle
from reportlab.lib.units import mm
from reportlab.platypus import BaseDocTemplate, Frame, NextPageTemplate, PageTemplate, Paragraph, Spacer

ROOT = Path(__file__).resolve().parent.parent
SCRIPTS_SRC = ROOT.parent / "03_Scripts-capsules"
OUT = ROOT / "scripts"
LOGO = ROOT / "assets" / "logo-imtbs.png"

VIOLET = HexColor("#AD1D89")
BLEU = HexColor("#00B8DE")
NOIR = HexColor("#111111")
GRIS = HexColor("#5B5B66")

TITLES = {
    "fr": {
        1: "Qu'est-ce que la technologie ?",
        2: "Qu'est-ce que l'innovation ?",
        3: "L'innovation, un enjeu économique et stratégique majeur",
        4: "L'innovation n'est pas uniquement technologique",
        5: "Les différents types d'innovation",
    },
    "en": {
        1: "What is technology?",
        2: "What is innovation?",
        3: "Innovation, a major economic and strategic issue",
        4: "Innovation is not only technological",
        5: "The different types of innovation",
    },
}

LABELS = {
    "fr": {
        "course": "MANAGEMENT DE L'INNOVATION",
        "capsule": "Capsule",
        "kind": "Script de la capsule vidéo",
        "note": "Script relu et validé par l'enseignant (septembre 2026). "
                "Dans la vidéo, l'image et la voix sont générées par un avatar IA de l'enseignant.",
        "footer": "Management de l'innovation · Benoît Tézenas du Montcel · Institut Mines-Télécom Business School",
    },
    "en": {
        "course": "INNOVATION MANAGEMENT",
        "capsule": "Capsule",
        "kind": "Video capsule script",
        "note": "English translation of the French script reviewed and approved by the instructor (September 2026). "
                "In the video, the image and voice are generated by an AI avatar of the instructor.",
        "footer": "Innovation Management · Benoît Tézenas du Montcel · Institut Mines-Télécom Business School",
    },
}

BAND_H = 52 * mm
TOP_WHITE = 24 * mm


def fr_text(n):
    folder = glob.glob(str(SCRIPTS_SRC / f"0{n}_*"))[0]
    md = Path(folder, "AIH_script.md").read_text(encoding="utf-8")
    return re.split(r"^---\s*$", md, flags=re.M)[1].strip()


def esc(s):
    return s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def draw_first_page(lang, n):
    lab = LABELS[lang]
    title = TITLES[lang][n]

    def _draw(c, doc):
        w, h = A4
        # Bandeau blanc avec logo
        c.drawImage(str(LOGO), 18 * mm, h - TOP_WHITE + 4 * mm, width=36 * mm, height=15.5 * mm,
                    preserveAspectRatio=True, mask="auto")
        c.setFillColor(GRIS)
        c.setFont("Helvetica", 8.5)
        c.drawRightString(w - 18 * mm, h - 14 * mm, lab["kind"])
        # Bandeau violet
        c.setFillColor(VIOLET)
        c.rect(0, h - TOP_WHITE - BAND_H, w, BAND_H, stroke=0, fill=1)
        c.setFillColor(BLEU)
        c.rect(0, h - TOP_WHITE - BAND_H, w, 2.2 * mm, stroke=0, fill=1)
        c.setFillColor(white)
        c.setFont("Helvetica-Bold", 9)
        c.drawString(18 * mm, h - TOP_WHITE - 14 * mm, lab["course"])
        c.setFillColor(BLEU)
        c.setFont("Helvetica-Bold", 15)
        c.drawString(18 * mm, h - TOP_WHITE - 24 * mm, f"{lab['capsule']} {n}")
        # Titre sur 1 ou 2 lignes
        c.setFillColor(white)
        size = 22
        words, lines, cur = title.split(), [], ""
        for wd in words:
            test = (cur + " " + wd).strip()
            if c.stringWidth(test, "Helvetica-Bold", size) > w - 36 * mm:
                lines.append(cur)
                cur = wd
            else:
                cur = test
        lines.append(cur)
        y = h - TOP_WHITE - 36 * mm
        for ln in lines:
            c.setFont("Helvetica-Bold", size)
            c.drawString(18 * mm, y, ln)
            y -= 9.5 * mm
        draw_footer(c, lang)

    return _draw


def draw_footer(c, lang):
    w, _ = A4
    c.setStrokeColor(BLEU)
    c.setLineWidth(0.6)
    c.line(18 * mm, 15 * mm, w - 18 * mm, 15 * mm)
    c.setFillColor(GRIS)
    c.setFont("Helvetica", 7.5)
    c.drawString(18 * mm, 10 * mm, LABELS[lang]["footer"])
    c.drawRightString(w - 18 * mm, 10 * mm, str(c.getPageNumber()))


def build(lang, n, text):
    OUT.mkdir(exist_ok=True)
    path = OUT / f"AIH_Capsule{n}_Script_{lang.upper()}.pdf"
    body = ParagraphStyle("body", fontName="Helvetica", fontSize=11, leading=15.5,
                          textColor=NOIR, spaceAfter=8)
    note = ParagraphStyle("note", fontName="Helvetica-Oblique", fontSize=8.5, leading=12,
                          textColor=GRIS, spaceBefore=10)
    w, h = A4
    doc = BaseDocTemplate(str(path), pagesize=A4,
                          title=f"{LABELS[lang]['course'].title()} – Capsule {n} – {TITLES[lang][n]}",
                          author="Benoît Tézenas du Montcel – IMT Business School",
                          subject=LABELS[lang]["kind"])
    first = Frame(18 * mm, 22 * mm, w - 36 * mm, h - TOP_WHITE - BAND_H - 10 * mm - 22 * mm, id="first")
    other = Frame(18 * mm, 22 * mm, w - 36 * mm, h - 20 * mm - 22 * mm, id="other")
    doc.addPageTemplates([
        PageTemplate(id="First", frames=[first], onPage=draw_first_page(lang, n)),
        PageTemplate(id="Later", frames=[other], onPage=lambda c, d: draw_footer(c, lang)),
    ])
    story = [NextPageTemplate("Later")]
    story += [Paragraph(esc(p), body) for p in text.split("\n\n") if p.strip()]
    story += [Spacer(1, 4 * mm), Paragraph(esc(LABELS[lang]["note"]), note)]
    doc.build(story)
    return path


def main():
    en = json.loads((ROOT / "tools" / "scripts_en.json").read_text(encoding="utf-8"))
    for n in range(1, 6):
        print(build("fr", n, fr_text(n)).name)
        print(build("en", n, en[str(n)]).name)


if __name__ == "__main__":
    main()
